using MassTransit;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using PharmacyDelivery.Domain.Abstract;
using PharmacyDelivery.Domain.Catalog;
using PharmacyDelivery.Domain.Common;
using PharmacyDelivery.Domain.Deliveries;
using PharmacyDelivery.Domain.Identity;
using PharmacyDelivery.Domain.Ordering;
using PharmacyDelivery.Domain.Payments;
using PharmacyDelivery.Domain.Pharmacies;
using PharmacyDelivery.Domain.Shared;
using PharmacyDelivery.Domain.Tracking;
using PharmacyDelivery.Repository.Auditing;
using PharmacyDelivery.Repository.Converters;

namespace PharmacyDelivery.Repository;

public sealed class PharmacyDeliveryDbContext(DbContextOptions<PharmacyDeliveryDbContext> options) : DbContext(options)
{
    public DbSet<Product> Products => Set<Product>();

    public DbSet<Pharmacy> Pharmacies => Set<Pharmacy>();

    public DbSet<StockItem> StockItems => Set<StockItem>();

    public DbSet<StockReservation> StockReservations => Set<StockReservation>();

    public DbSet<Order> Orders => Set<Order>();

    public DbSet<OrderItem> OrderItems => Set<OrderItem>();

    public DbSet<OrderStatusChange> OrderStatusHistory => Set<OrderStatusChange>();

    public DbSet<Payment> Payments => Set<Payment>();

    public DbSet<Courier> Couriers => Set<Courier>();

    public DbSet<Delivery> Deliveries => Set<Delivery>();

    public DbSet<User> Users => Set<User>();

    public DbSet<AuthSession> AuthSessions => Set<AuthSession>();

    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();

    public DbSet<AccessToken> AccessTokens => Set<AccessToken>();

    public DbSet<PasswordHistoryEntry> PasswordHistory => Set<PasswordHistoryEntry>();

    public DbSet<CourierLocationRecord> CourierLocations => Set<CourierLocationRecord>();

    public DbSet<AuditEntry> AuditEntries => Set<AuditEntry>();

    public DbSet<AuditChange> AuditChanges => Set<AuditChange>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        // Strongly typed ids are stored as uuid; enums as readable strings.
        configurationBuilder.Properties<ProductId>().HaveConversion<ProductIdConverter>();
        configurationBuilder.Properties<PharmacyId>().HaveConversion<PharmacyIdConverter>();
        configurationBuilder.Properties<OrderId>().HaveConversion<OrderIdConverter>();
        configurationBuilder.Properties<CourierId>().HaveConversion<CourierIdConverter>();
        configurationBuilder.Properties<DeliveryId>().HaveConversion<DeliveryIdConverter>();
        configurationBuilder.Properties<UserId>().HaveConversion<UserIdConverter>();
        configurationBuilder.Properties<GeoPoint>().HaveConversion<GeoPointConverter>().HaveColumnType("geography(Point,4326)");
        configurationBuilder.Properties<Enum>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<decimal>().HavePrecision(12, 2);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasPostgresExtension("postgis");
        modelBuilder.HasPostgresExtension("pg_trgm");
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(PharmacyDeliveryDbContext).Assembly);

        // MassTransit transactional outbox/inbox tables (same database, same transaction).
        modelBuilder.AddInboxStateEntity();
        modelBuilder.AddOutboxMessageEntity();
        modelBuilder.AddOutboxStateEntity();

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(t => typeof(IAggregateRoot).IsAssignableFrom(t.ClrType)))
            modelBuilder.Entity(entityType.ClrType).Ignore(nameof(IAggregateRoot.DomainEvents));

        // Ids are generated by the application (Guid v7), never by the database. Without this, an entity with a set
        // key that is added to a tracked aggregate's collection (e.g. a new status history row) would be treated as
        // existing and UPDATEd instead of INSERTed.
        foreach (var key in modelBuilder.Model.GetEntityTypes().Where(t => !t.IsOwned()).Select(t => t.FindPrimaryKey())
                     .OfType<IMutableKey>())
        {
            foreach (var property in key.Properties.Where(p => p.ClrType != typeof(long) && p.ClrType != typeof(int)))
                property.ValueGenerated = ValueGenerated.Never;
        }
    }
}
